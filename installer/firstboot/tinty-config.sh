#!/usr/bin/env bash
# Writes tinty's config.toml from config.base.toml (shipped by sobarch-skel)
# plus local.toml (the user's own items). tinty reads a single file and has
# no include, so the two are concatenated.

set -euo pipefail

dir="$HOME/.config/tinted-theming/tinty"
base="$dir/config.base.toml"
extra="$dir/local.toml"
out="$dir/config.toml"

[[ -r "$base" ]] || exit 0

tmp="$(mktemp "$dir/.config.toml.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

assemble() {
    {
        echo "# Generated by tinty-config.sh from config.base.toml and local.toml."
        echo "# Edit local.toml, not this file."
        echo
        cat "$base"
        if [[ "$1" == with-local && -r "$extra" ]]; then
            printf '\n# --- local.toml ---\n\n'
            cat "$extra"
        fi
    } >"$tmp"
}

assemble with-local
# A broken local.toml must not take the whole theme switcher down with it.
if command -v tinty >/dev/null && ! err="$(tinty -c "$tmp" config --config-path 2>&1 >/dev/null)"; then
    echo "tinty-config: ignoring $extra, it doesn't parse:" >&2
    echo "$err" >&2
    assemble base-only
fi

if cmp -s "$tmp" "$out"; then
    exit 0
fi
mv -f "$tmp" "$out"
