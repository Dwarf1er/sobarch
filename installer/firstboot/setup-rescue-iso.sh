#!/usr/bin/env bash
# First-boot half of the rescue media setup: fills the partitions that
# rescue-iso-setup.sh formatted at install time, then adds the Limine entry.
# The entry is only added once the files exist. rescue-pending stays on
# failure so the next network "up" retries.

set -euo pipefail

[ -e /etc/sobarch/rescue-pending ] || exit 0

/usr/local/lib/sobarch/refresh-rescue-iso.sh

RESCUE_DEV="$(blkid -L RESCUE)"
RESCUE_UUID=$(blkid -s UUID -o value "$RESCUE_DEV")

if [ -d /sys/firmware/efi ]; then
# Limine's uuid() needs a full 128-bit ID. FAT32's blkid "UUID" is only a
# 32-bit serial, so use the GPT PARTUUID.
    RESCUE_BOOT_PARTUUID=$(blkid -s PARTUUID -o value "$(blkid -L RESCUEBOOT)")
    KERNEL_PATH="uuid(${RESCUE_BOOT_PARTUUID}):/vmlinuz-linux"
    INITRD_PATH="uuid(${RESCUE_BOOT_PARTUUID}):/initramfs-linux.img"
    LIMINE_CONF="/boot/EFI/BOOT/limine.conf"
else
    KERNEL_PATH="boot():/rescue/vmlinuz-linux"
    INITRD_PATH="boot():/rescue/initramfs-linux.img"
    LIMINE_CONF="/boot/limine/limine.conf"
fi

START_MARKER="#### SOBARCH RESCUE ENTRY START (auto-generated by setup-rescue-iso.sh, do not edit by hand)"
END_MARKER="#### SOBARCH RESCUE ENTRY END"

# Separate block from the snapshot entries so neither regeneration clobbers the other.
block="$START_MARKER
/Arch Linux rescue (local ISO)
    protocol: linux
    path: ${KERNEL_PATH}
    module_path: ${INITRD_PATH}
    cmdline: archisobasedir=arch img_dev=UUID=${RESCUE_UUID} img_loop=/archlinux-x86_64.iso
$END_MARKER"

if grep -qF "$START_MARKER" "$LIMINE_CONF"; then
    awk -v start="$START_MARKER" -v end="$END_MARKER" -v block="$block" '
        $0 == start { print block; skipping = 1; next }
        $0 == end && skipping { skipping = 0; next }
        skipping { next }
        { print }
    ' "$LIMINE_CONF" > "${LIMINE_CONF}.sobarch-new"
    mv "${LIMINE_CONF}.sobarch-new" "$LIMINE_CONF"
else
    printf '\n%s\n' "$block" >> "$LIMINE_CONF"
fi

rm -f /etc/sobarch/rescue-pending
echo "setup-rescue-iso: done."
